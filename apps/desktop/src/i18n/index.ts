export const LANGUAGE_STORAGE_KEY = "mediaatlas.language";
export type AppLocale = "zh-CN" | "en-US";
export function readStoredLanguage(): AppLocale {
  try {
    const value = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return value === "en-US" || value === "en" ? "en-US" : "zh-CN";
  } catch {
    return "zh-CN";
  }
}
export function persistLanguage(value: string): void {
  try {
    localStorage.setItem(
      LANGUAGE_STORAGE_KEY,
      value === "en" || value === "en-US" ? "en-US" : "zh-CN",
    );
  } catch {
    /* Storage may be unavailable in private mode. */
  }
}

